#!/usr/bin/env node
/* Generates the CSS custom properties from design/tokens.json. Nothing else defines these values. */
import { readFileSync, writeFileSync } from 'node:fs'

const tokens = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'))
const colours = set => Object.entries(set).map(([name, value]) => `  --${name}: #${value.toLowerCase()};`)
const scale = (prefix, values) => Object.entries(values).map(([name, value]) => `  --${prefix}-${name}: ${value}px;`)

for (const name of Object.keys(tokens.dark)) {
  if (!(name in tokens.colour)) throw new Error(`Dark token "${name}" has no light value`)
}

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${colours(tokens.colour).join('\n')}
${scale('space', tokens.space).join('\n')}
${scale('radius', tokens.radius).join('\n')}
  --motion-feedback: ${tokens.motion.feedback}ms;
  --motion-page: ${tokens.motion.page}ms;
  --motion-hand-off: ${tokens.motion['hand-off']}ms;
  --easing: ${tokens.motion.easing};
}

/* The dark theme, chosen with the header toggle and remembered. */
:root[data-theme='dark'] {
  color-scheme: dark;
${colours(tokens.dark).join('\n')}
}
`
writeFileSync(new URL('../app/assets/css/tokens.css', import.meta.url), css)
